      const catPts = { comm: 0, val: 0, intim: 0, conf: 0, fut: 0 };

      QUESTIONS.forEach((q, idx) => {
        const choiceIdx = answers[idx] !== null ? answers[idx] : 2;
        const pts = q[currentLang].options[choiceIdx].points;
        totalPts += pts;
        catPts[q.category] += pts;
      });

      const totalScorePercent = Math.min(100, Math.max(10, Math.round((totalPts / 45) * 100)));

      // 5 Categories: 3 questions each -> max 9 pts
      const commScore = Math.round((catPts.comm / 9) * 100);
      const valScore = Math.round((catPts.val / 9) * 100);
      const intimScore = Math.round((catPts.intim / 9) * 100);
      const confScore = Math.round((catPts.conf / 9) * 100);
      const futScore = Math.round((catPts.fut / 9) * 100);

      // Display couple names
