    function showToast(message) {
      toastMsg.textContent = message;
      toast.classList.add('show');
      setTimeout(() => {
        toast.classList.remove('show');
      }, 3200);
    }

    function applyTranslations() {
      const dict = I18N[currentLang];
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
          el.textContent = dict[key];
        }
      });
      langFlag.textContent = currentLang === 'fr' ? '🇫🇷' : '🇬🇧';
      langCode.textContent = currentLang.toUpperCase();
      document.documentElement.lang = currentLang;

      // Update question text if currently on questions screen
      if (sectionQuestions.style.display === 'block') {
        renderQuestion(currentStep);
      }
    }

    function saveState() {
      try {
        const payload = {
          currentStep,
          answers,
          partner1,
          partner2,
          relationType,
          savedAt: Date.now()
        };
        localStorage.setItem('lovequiz_session', JSON.stringify(payload));
        showToast(I18N[currentLang].toastSaved);
      } catch(e) {}
    }

    function checkSavedState() {
      try {
        const raw = localStorage.getItem('lovequiz_session');
        if (!raw) return false;
        const data = JSON.parse(raw);
        if (data && Array.isArray(data.answers) && data.answers.some(a => a !== null)) {
          return data;
        }
      } catch(e) {}
      return false;
    }

